"""Import and verify the licensed ZX Spectrum sources and regenerate its ULA port."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "third_party/zx-spectrum/upstream"
MANIFEST = ROOT / "provenance/zx-spectrum.import.json"
PORTS = ROOT / "hdl/core/zx_spectrum/ports"
URL = "https://github.com/MiSTer-devel/ZX-Spectrum_MISTer.git"
PIN = "8502d492a3ad89c68413b2f0e2e4cf947dab42ba"
FILES = {
    "ZX-Spectrum.sv": "GPL-2.0-or-later",
    "rtl/ula.sv": "GPL-3.0-or-later",
    "rtl/ym2149.sv": "BSD-3-Clause",
    **{f"rtl/T80/{name}.vhd": "BSD-3-Clause" for name in (
        "T80_Pack", "T80_ALU", "T80_MCode", "T80_Reg", "T80", "T80pa"
    )},
}


def read_pinned(checkout: Path, path: str) -> bytes:
    # The pinned Git object ID also allows verification of a sparse working
    # directory populated with GitHub's raw files and no local blob objects.
    entry = subprocess.check_output(
        ["git", "-C", str(checkout), "ls-tree", PIN, "--", path], text=True
    ).split()
    data = (checkout / path).read_bytes()
    blob = hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()
    if len(entry) != 4 or entry[1] != "blob" or entry[2] != blob:
        raise SystemExit(f"Pinned source mismatch for {path}; check out with core.autocrlf=false")
    return data


def adapt(data: bytes, replacements: dict[str, str]) -> bytes:
    source = data.decode().replace("\r\n", "\n")
    for original, adapted in replacements.items():
        if source.count(original) != 1:
            raise SystemExit(f"Could not apply ZX Spectrum port change for {original!r}")
        source = source.replace(original, adapted)
    return ("// Generated by scripts/port_zx_spectrum_core.py\n" + source).encode()


def port_ula(data: bytes) -> bytes:
    return adapt(data, {
        "module ULA\n": "module multitini_zx_spectrum_ula\n",
        "\toutput reg    HSync,": "\toutput [8:0]  raster_h, raster_v,\n\toutput reg    HSync,",
        "assign vram_addr = vaddr;": "assign raster_h  = hc;\nassign raster_v  = vc;\nassign vram_addr = vaddr;",
        "reg  [4:0] FlashCnt;": "reg  [4:0] FlashCnt = 0;",
        "reg  CPUClk;": "reg  CPUClk = 0;",
        "reg  next_clk_r;": "reg  next_clk_r = 0;",
    })


def port_psg(data: bytes) -> bytes:
    # The upstream register reset leaves the divider and generators running.
    # Give their phase and seed a defined state on cold and warm reset.
    return adapt(data, {
        "\tif(CE) begin\n\t\tena_div <= 0;":
            "\tif(RESET) begin\n\t\tcnt_div <= 0;\n\t\tnoise_div <= 0;\n"
            "\t\tena_div <= 0;\n\t\tena_div_noise <= 0;\n\tend else if(CE) begin\n\t\tena_div <= 0;",
        "\tif(CE) begin\n\t\tif (ena_div_noise)":
            "\tif(RESET) begin\n\t\tpoly17 <= 0;\n\t\tnoise_gen_cnt <= 0;\n"
            "\t\tnoise_gen_op <= 0;\n\tend else if(CE) begin\n\t\tif (ena_div_noise)",
        "\tif(CE) begin\n\t\t// looks like real chips count up":
            "\tif(RESET) begin\n\t\ttone_gen_cnt <= '{default:0};\n\t\ttone_gen_op <= 0;\n"
            "\tend else if(CE) begin\n\t\t// looks like real chips count up",
        "\tif(CE) begin\n\t\tenv_ena <= 0;":
            "\tif(RESET) begin\n\t\tenv_gen_cnt <= 0;\n\t\tenv_ena <= 0;\n"
            "\tend else if(CE) begin\n\t\tenv_ena <= 0;",
    })


def write_or_check(path: Path, data: bytes, check: bool) -> None:
    if check:
        if not path.is_file() or path.read_bytes().replace(b"\r\n", b"\n") != data:
            raise SystemExit(f"ZX Spectrum generated file differs: {path.relative_to(ROOT)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--import-checkout", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    records = []
    for path, license_id in FILES.items():
        target = UPSTREAM / path
        if args.import_checkout:
            data = read_pinned(args.import_checkout, path)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
            elif target.read_bytes() != data:
                raise SystemExit(f"Imported source differs: {path}")
        else:
            data = target.read_bytes()
        records.append({"path": path, "sha256": hashlib.sha256(data).hexdigest(),
                        "license": license_id, "license_evidence": "File-local grant"})
    manifest = {"schema_version": 1, "source": URL, "commit": PIN,
                "purpose": "ULA, Z80 and AY PSG. ZX-Spectrum.sv is reference only.",
                "exclusions": ["MiSTer platform and generated IP", "system ROMs, media and bitstreams",
                               "NonCommercial upstream keyboard", "other machine variants and expansions"],
                "files": records}
    # A rebuild verifies existing upstream hashes before adapting any source.
    manifest_data = (json.dumps(manifest, indent=2) + "\n").encode()
    write_or_check(MANIFEST, manifest_data, args.check or args.import_checkout is None)
    for name, generator in (("ula.sv", port_ula), ("ym2149.sv", port_psg)):
        write_or_check(PORTS / name, generator((UPSTREAM / "rtl" / name).read_bytes()), args.check)


if __name__ == "__main__":
    main()
