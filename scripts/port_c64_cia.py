"""Reproduce the local C64 CIA timer reload-window correction from its pin."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/c64/upstream/rtl/mos6526.v"
TARGET = ROOT / "hdl/core/c64/ports/mos6526.v"
COMMIT = "62fc697e3c9b5982c9dc76aa8cd03db545d20803"


def validate_reference() -> None:
    manifest = json.loads((ROOT / "third_party/c64/import_manifest.json").read_text())
    lock = json.loads((ROOT / "provenance/imports.lock.json").read_text())
    entries = [entry for entry in lock["imports"]
               if entry["path"] == SOURCE.relative_to(ROOT).as_posix()]
    if (manifest["source"]["commit"] != COMMIT or len(entries) != 1 or
            entries[0]["source"] != "MiSTer C64" or
            entries[0]["source_path"] != "rtl/mos6526.v" or
            hashlib.sha256(SOURCE.read_bytes()).hexdigest() != entries[0]["sha256"]):
        raise ValueError("Pinned C64 CIA source does not match its import lock")


def replace_once(source: str, before: str, after: str) -> str:
    if source.count(before) != 1:
        raise ValueError("Pinned CIA port anchor changed: " + before.splitlines()[0])
    return source.replace(before, after, 1)


def port(source: str) -> str:
    for timer in ("A", "B"):
        suffix = timer.lower()
        source = replace_once(source, f"reg timer{timer}ff;",
                              f"reg timer{timer}ff;\nreg reload{timer};")
        source = replace_once(source, f"    timer{timer}ff       <= 1'b0;",
                              f"    timer{timer}ff       <= 1'b0;\n    reload{timer}        <= 1'b0;")
        source = replace_once(source, f"      count{timer}0 <= cnt_in_r && ~cnt_in_prev;",
                              "      // Keep a completed reload visible through the following bus phase.\n"
                              f"      reload{timer} <= timer{timer}overflow | load{timer}1;\n"
                              f"      count{timer}0 <= cnt_in_r && ~cnt_in_prev;")
        source = replace_once(source,
                              f"            if (timer{timer}overflow) timer_{suffix} <= {{t{suffix}_hi, db_in}};",
                              f"            if (reload{timer}) timer_{suffix}[7:0] <= db_in;")
        source = replace_once(source, f"            if (~cr{suffix}[0]) begin",
                              f"            if (~cr{suffix}[0] || reload{timer}) begin")
    # The upstream PB output block refers to these nets before declaration.
    # Local HDL is compiled without relaxed imported-source parsing.
    declarations = []
    for timer in ("A", "B"):
        begin = source.index(f"// Timer {timer}\n") + len(f"// Timer {timer}\n")
        end = source.index("\nalways @(posedge clk) begin", begin)
        declarations.append(source[begin:end].strip())
        source = source[:begin] + source[end + 1:]
    source = replace_once(source, "wire       rd = phi2_n & !cs_n & rw;",
                          "// Timer nets are shared with the earlier PB output block.\n" +
                          "\n\n".join(declarations) + "\n\n" +
                          "wire       rd = phi2_n & !cs_n & rw;")
    return ("// Generated by scripts/port_c64_cia.py; do not edit directly.\n"
            f"// Source: MiSTer C64 {COMMIT}.\n"
            "// Local changes: timer reload-window bypass and declaration ordering.\n"
            "// Upstream notices and all other logic are retained below.\n" + source)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    validate_reference()
    expected = port(SOURCE.read_text())
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != expected:
            raise SystemExit("C64 CIA port differs from its pinned deterministic generation")
        print("PASS: C64 CIA port is reproducible from pinned source")
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
        print(TARGET.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
