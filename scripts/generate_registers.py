#!/usr/bin/env python3
"""Generate the C and SystemVerilog register ABI from one JSON source."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "spec" / "interface_v0.json"
C_PATH = ROOT / "firmware" / "include" / "multitini_regs.h"
SV_PATH = ROOT / "hdl" / "generated" / "multitini_regs_pkg.sv"
ACCESS = {"ro", "rw", "rw1c", "wo"}


def number(value: int | str) -> int:
    if isinstance(value, int):
        return value
    return int(value, 0)


def load_spec() -> dict:
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    if spec.get("schema_version") != 1:
        raise ValueError("unsupported interface schema")

    span = number(spec["register_span"])
    offsets: set[int] = set()
    names: set[str] = set()
    for register in spec["registers"]:
        name = register["name"]
        offset = number(register["offset"])
        if not name.isidentifier() or name.upper() != name:
            raise ValueError(f"invalid register name: {name}")
        if name in names:
            raise ValueError(f"duplicate register name: {name}")
        if offset in offsets:
            raise ValueError(f"duplicate register offset: 0x{offset:03X}")
        if offset & 3 or offset < 0 or offset >= span:
            raise ValueError(f"invalid register offset: {name}=0x{offset:X}")
        if register["access"] not in ACCESS:
            raise ValueError(f"invalid access for {name}: {register['access']}")
        names.add(name)
        offsets.add(offset)

    for register_name, fields in spec["bitfields"].items():
        if register_name not in names:
            raise ValueError(f"bitfield refers to unknown register: {register_name}")
        bits: set[int] = set()
        for field_name, bit in fields.items():
            if not field_name.isidentifier() or field_name.upper() != field_name:
                raise ValueError(f"invalid field name: {field_name}")
            if not isinstance(bit, int) or bit < 0 or bit > 31 or bit in bits:
                raise ValueError(f"invalid or duplicate bit: {register_name}.{field_name}")
            bits.add(bit)

    return spec


def render_c(spec: dict) -> str:
    major = number(spec["abi"]["major"])
    minor = number(spec["abi"]["minor"])
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* Generated by scripts/generate_registers.py. Do not edit. */",
        "#ifndef MULTITINI_REGS_H",
        "#define MULTITINI_REGS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define MT_ABI_MAJOR {major}U",
        f"#define MT_ABI_MINOR {minor}U",
        "#define MT_ABI_VERSION ((MT_ABI_MAJOR << 16) | MT_ABI_MINOR)",
        f"#define MT_MAGIC UINT32_C(0x{number(spec['magic']):08X})",
        f"#define MT_SHELL_ID UINT32_C(0x{number(spec['shell_id']):08X})",
        f"#define MT_REGISTER_SPAN UINT32_C(0x{number(spec['register_span']):08X})",
        "",
    ]
    for register in spec["registers"]:
        lines.append(
            f"#define MT_REG_{register['name']} UINT32_C(0x{number(register['offset']):03X})"
        )

    for register_name, fields in spec["bitfields"].items():
        lines.append("")
        for field_name, bit in fields.items():
            lines.append(
                f"#define MT_{register_name}_{field_name} (UINT32_C(1) << {bit})"
            )

    for group, prefix in (("commands", "MT_COMMAND"), ("responses", "MT_RESPONSE")):
        lines.append("")
        for name, value in spec[group].items():
            lines.append(f"#define {prefix}_{name} UINT32_C(0x{number(value):08X})")

    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def render_sv(spec: dict) -> str:
    major = number(spec["abi"]["major"])
    minor = number(spec["abi"]["minor"])
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// Generated by scripts/generate_registers.py. Do not edit.",
        "`timescale 1ns / 1ps",
        "package multitini_regs_pkg;",
        f"    localparam logic [15:0] MT_ABI_MAJOR = 16'd{major};",
        f"    localparam logic [15:0] MT_ABI_MINOR = 16'd{minor};",
        "    localparam logic [31:0] MT_ABI_VERSION = {MT_ABI_MAJOR, MT_ABI_MINOR};",
        f"    localparam logic [31:0] MT_MAGIC = 32'h{number(spec['magic']):08X};",
        f"    localparam logic [31:0] MT_SHELL_ID = 32'h{number(spec['shell_id']):08X};",
        f"    localparam int unsigned MT_REGISTER_SPAN = 32'h{number(spec['register_span']):08X};",
        "",
    ]
    for register in spec["registers"]:
        lines.append(
            f"    localparam logic [11:0] MT_REG_{register['name']} = 12'h{number(register['offset']):03X};"
        )

    for register_name, fields in spec["bitfields"].items():
        lines.append("")
        for field_name, bit in fields.items():
            lines.append(
                f"    localparam logic [31:0] MT_{register_name}_{field_name} = 32'h{1 << bit:08X};"
            )

    for group, prefix in (("commands", "MT_COMMAND"), ("responses", "MT_RESPONSE")):
        lines.append("")
        for name, value in spec[group].items():
            lines.append(
                f"    localparam logic [31:0] {prefix}_{name} = 32'h{number(value):08X};"
            )

    lines.extend(["endpackage", ""])
    return "\n".join(lines)


def update(path: Path, expected: str, check: bool) -> bool:
    actual = path.read_text(encoding="utf-8") if path.exists() else None
    if actual == expected:
        return True
    if check:
        print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8")
    print(f"generated {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load_spec()
    good = update(C_PATH, render_c(spec), args.check)
    good = update(SV_PATH, render_sv(spec), args.check) and good
    return 0 if good else 1


if __name__ == "__main__":
    raise SystemExit(main())
