"""Compile pinned MAME 6510 execution code in a bounded, flat-memory harness.

The opcode generator, opcode bodies, ALU, prefetch, interrupt sampling and port
methods come from MAME. This is a CPU/port oracle, not the full MAME C64 machine.
It never downloads ROMs and never treats unavailable reference tools as a pass.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "third_party/mame_reference"
SOURCE = REFERENCE / "upstream/src/devices/cpu/m6502"
COMMIT = "122719e8d13e2fdb7dd33886455484207de59fc8"


def function(source: str, name: str) -> str:
    match = re.search(r"^(?:void|int|uint8_t|offs_t) " + re.escape(name) + r"\([^\n]*\)\n\{", source, re.M)
    if not match:
        raise ValueError(f"Pinned source function not found: {name}")
    start, cursor = match.start(), match.end()
    depth = 1
    while depth:
        if source[cursor] == "{": depth += 1
        elif source[cursor] == "}": depth -= 1
        cursor += 1
    return source[start:cursor]


def generate(output: Path) -> None:
    # Source imports are immutable; generated bytecode belongs nowhere in the
    # pinned subset. The generated C++ goes only into the selected build dir.
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location("pinned_mame_generator", SOURCE / "m6502make.py")
    assert spec and spec.loader
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    opcodes = generator.load_opcodes(str(SOURCE / "om6502.lst"))
    opcodes += generator.load_opcodes(str(SOURCE / "om6510.lst"))
    states = generator.load_disp(str(SOURCE / "dm6510.lst"))
    # Flattening the inheritance preserves the exact generated opcode bodies.
    generator.saves(str(output / "mame_opcodes.inc"), "m6502", opcodes, states)
    cpu_notice = ("// Generated from pinned MAME source. license:BSD-3-Clause\n"
                  "// copyright-holders:Olivier Galibert\n")
    generated = output / "mame_opcodes.inc"
    generated.write_text(cpu_notice + generated.read_text(encoding="utf-8"), encoding="utf-8")
    declarations = "\n".join(f"void {name}_full(); void {name}_partial();" for name, _ in opcodes)
    base = (SOURCE / "m6502.cpp").read_text(encoding="utf-8")
    port = (SOURCE / "m6510.cpp").read_text(encoding="utf-8")
    names = re.findall(r"^(?:void|uint8_t) m6502_device::(do_\w+|set_nz)\(", base, re.M)
    names += ["device_reset", "execute_run", "execute_set_input", "prefetch_start", "prefetch_end", "prefetch_end_noirq"]
    bodies = [function(base, "m6502_device::" + name) for name in names]
    bodies += [function(port, "m6510_device::" + name).replace("m6510_device::", "m6502_device::")
               for name in ["update_port", "get_port", "dir_r", "dir_w", "port_r", "port_w",
                            "set_pulls", "set_floating_falloff"]]
    bodies += [function(port, "m6510_device::device_reset").replace(
        "m6510_device::device_reset", "m6502_device::reset_port")]
    declarations += "\n" + "\n".join(body.split("\n", 1)[0].replace("m6502_device::", "") + ";" for body in bodies)
    # The instruction-independent startup register values also come verbatim
    # from MAME init(), excluding MAME's framework registration and save hooks.
    init = function(base, "m6502_device::init")
    initialization = init[init.index("\tm_XPC = 0x0000;"):init.rindex("}")]
    (output / "mame_declarations.inc").write_text(cpu_notice + declarations + "\n", encoding="utf-8")
    (output / "mame_methods.inc").write_text(cpu_notice + "\n\n".join(bodies) + "\n", encoding="utf-8")
    (output / "mame_initialization.inc").write_text(cpu_notice + initialization, encoding="utf-8")
    header = (SOURCE / "m6502.h").read_text(encoding="utf-8")
    helpers = ["sample_interrupt", "page_changing", "set_l", "set_h", "dec_SP", "inc_SP",
               "read_pc", "read_pc_noirq", "read_arg_noirq"]
    inline = []
    for name in helpers:
        found = [line.strip() for line in header.splitlines()
                 if re.search(r"\b" + name + r"\([^)]*\)\s*\{", line)]
        if len(found) != 1:
            raise ValueError(f"Expected one exact inline helper: {name}")
        inline.extend(found)
    (output / "mame_inline.inc").write_text(cpu_notice + "\n".join(inline) + "\n", encoding="utf-8")
    machine = (REFERENCE / "upstream/src/mame/commodore/c64.cpp").read_text(encoding="utf-8")
    memory = [function(machine, "c64_state::" + name)
              for name in ["read_pla", "read_memory", "write_memory"]]
    (output / "mame_memory.inc").write_text(
        "// Extracted from pinned MAME source. license:BSD-3-Clause\n// copyright-holders:Curt Coder\n"
        + "\n\n".join(memory) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build/c64-mame-oracle")
    parser.add_argument("--compiler", type=Path)
    parser.add_argument("--image", type=Path)
    parser.add_argument("--trace", type=Path)
    parser.add_argument("--start", default="0800")
    parser.add_argument("--stop-address", default="0204")
    parser.add_argument("--stop-data", default="a5")
    parser.add_argument("--port-input", default="a0")
    parser.add_argument("--max-cycles", type=int, default=100000)
    parser.add_argument("--events", type=Path, help="Optional text: cycle ready irq nmi (decimal)")
    args = parser.parse_args()
    output = args.build_dir.resolve()
    if not output.is_relative_to((ROOT / "build").resolve()):
        parser.error("--build-dir must remain inside this checkout's ignored build/")
    output.mkdir(parents=True, exist_ok=True)
    (output / "receipt.json").unlink(missing_ok=True)
    manifest_path = REFERENCE / "import_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    harness_files = [Path(__file__).resolve(), ROOT / "tests/c64_mame/oracle_harness.cpp",
                     ROOT / "tests/c64_mame/memory_harness.cpp", ROOT / "scripts/run_native_tool.py"]
    source_files = [manifest_path, *harness_files,
                    *[REFERENCE / "upstream" / entry["path"] for entry in manifest["files"]]]
    def source_hashes() -> dict[str, str]:
        return {path.relative_to(ROOT).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
                for path in source_files}
    initial_source_hashes = source_hashes()
    for entry in manifest["files"]:
        path = REFERENCE / "upstream" / entry["path"]
        if hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
            raise RuntimeError(f"Pinned MAME source changed: {entry['path']}")
    generate(output)
    compiler = args.compiler or shutil.which("g++")
    if not compiler and os.name == "nt":
        compiler = Path(os.environ.get("MULTITINI_UCRT_BIN", "C:/msys64/ucrt64/bin")) / "g++.exe"
    if not compiler or not Path(compiler).is_file():
        raise RuntimeError("A C++17 compiler is required; use --compiler")
    executable = output / ("mame6510_oracle.exe" if os.name == "nt" else "mame6510_oracle")
    command = [str(compiler), "-std=c++17", "-O2", "-Wall", "-Wextra", "-Wno-implicit-fallthrough",
               "-I", str(output), str(ROOT / "tests/c64_mame/oracle_harness.cpp"), "-o", str(executable)]
    guard = [sys.executable, str(ROOT / "scripts/run_native_tool.py"), "--"]
    subprocess.run(guard + command, check=True)
    memory_executable = output / ("mame_c64_memory_oracle.exe" if os.name == "nt" else "mame_c64_memory_oracle")
    memory_command = [str(compiler), "-std=c++17", "-O2", "-Wall", "-Wextra", "-I", str(output),
                      str(ROOT / "tests/c64_mame/memory_harness.cpp"), "-o", str(memory_executable)]
    subprocess.run(guard + memory_command, check=True)
    memory_csv = output / "memory_handlers.csv"
    subprocess.run(guard + [str(memory_executable), str(memory_csv)], check=True)
    receipt = {"reference_commit": COMMIT, "scope": "MAME 6510 CPU and port in flat-memory harness",
               "compiler": str(compiler), "executable_sha256": hashlib.sha256(executable.read_bytes()).hexdigest(),
               "source_files": manifest["files"], "trace_generated": False,
               "memory_handlers": {"scope": "Actual C64 handlers with supplied PLA output; no PLA truth-table or peripheral model proof",
                   "vectors": str(memory_csv), "vectors_sha256": hashlib.sha256(memory_csv.read_bytes()).hexdigest(),
                   "executable_sha256": hashlib.sha256(memory_executable.read_bytes()).hexdigest()}}
    receipt["harness_sha256"] = {p.relative_to(ROOT).as_posix(): initial_source_hashes[p.relative_to(ROOT).as_posix()]
                                  for p in harness_files}
    receipt["generated_sha256"] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                                    for p in sorted(output.glob("mame_*.inc"))}
    receipt["compile_commands"] = [command, memory_command]
    if args.image:
        image_hash = hashlib.sha256(args.image.read_bytes()).hexdigest()
        events_hash = hashlib.sha256(args.events.read_bytes()).hexdigest() if args.events else None
        trace = (args.trace or output / "trace.csv").resolve()
        trace.parent.mkdir(parents=True, exist_ok=True)
        run = [str(executable), str(args.image.resolve()), str(trace), args.start,
               args.stop_address, args.stop_data, args.port_input, str(args.max_cycles)]
        if args.events: run += [str(args.events.resolve())]
        subprocess.run(guard + run, check=True)
        if hashlib.sha256(args.image.read_bytes()).hexdigest() != image_hash:
            raise RuntimeError("Oracle input image changed during execution")
        if args.events and hashlib.sha256(args.events.read_bytes()).hexdigest() != events_hash:
            raise RuntimeError("Oracle input events changed during execution")
        receipt.update(trace_generated=True, image_sha256=image_hash,
                       trace=str(trace), trace_sha256=hashlib.sha256(trace.read_bytes()).hexdigest(),
                       command=run)
        if args.events: receipt["events_sha256"] = events_hash
    current_source_hashes = source_hashes()
    changed = [path for path, digest in initial_source_hashes.items() if current_source_hashes.get(path) != digest]
    if changed:
        raise RuntimeError("Oracle sources changed during validation: " + ", ".join(changed))
    receipt["source_sha256"] = initial_source_hashes
    (output / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"executable": str(executable), "receipt": str(output / 'receipt.json')}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
