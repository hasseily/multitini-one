#ifndef MULTITINI_AMIGA_INTERFACE_H
#define MULTITINI_AMIGA_INTERFACE_H
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#define MT_AMIGA_CORE_ID UINT32_C(0x414d4947)
#define MT_LOAD_AMIGA_CONFIG 0x60U
#define MT_LOAD_AMIGA_KICKSTART 0x61U
#define MT_AMIGA_CONFIG_BYTES 16U
#define MT_AMIGA_ROM_BYTES 1048576U
#define MT_AMIGA_ADF_BYTES 901120U
#define MT_AMIGA_SECTOR_BYTES 512U
#define MT_AMIGA_DRIVE_COUNT 4U
#define MT_AMIGA_MEDIA_NAME_MAX 191U
#define MT_AMIGA_HOST_PORT UINT32_C(0xd000)
#define MT_AMIGA_HOST_BUSY UINT32_C(0x80000000)
#define MT_AMIGA_HOST_ERROR UINT32_C(0x40000000)
#define MT_AMIGA_HOST_TOGGLE UINT32_C(0x20000000)
#define MT_AMIGA_HOST_RTC UINT32_C(0x10000000)
#define MT_AMIGA_INPUT_KEYBOARD UINT16_C(0x6000)
#define MT_AMIGA_INPUT_MOUSE_X UINT16_C(0x6100)
#define MT_AMIGA_INPUT_MOUSE_Y UINT16_C(0x6101)
#define MT_AMIGA_INPUT_MOUSE_BUTTONS UINT16_C(0x6102)
#define MT_AMIGA_INPUT_JOYSTICK UINT16_C(0x6200)
/* Native host port: command opcode[31:24], payload[23:0]. SELECT uses
 * payload bits0=FPGA,1=UIO. TRANSFER preserves SELECT until changed. */
enum { MT_AMIGA_HOST_SELECT=0, MT_AMIGA_HOST_TRANSFER=1,
    MT_AMIGA_HOST_IDE_READ=2, MT_AMIGA_HOST_IDE_WRITE=3,
    MT_AMIGA_HOST_CLEAR_ERROR=4,MT_AMIGA_HOST_RTC_LOW=5,
    MT_AMIGA_HOST_RTC_MIDDLE=6,MT_AMIGA_HOST_RTC_COMMIT=7 };
enum { MT_AMIGA_CPU_STOCK=0, MT_AMIGA_CPU_68000_TURBO=1,
    MT_AMIGA_CPU_68020_TURBO=2 };
typedef struct {
    uint8_t cpu, ntsc, fast_blitter, floppy_turbo, fast_mib;
} mt_amiga_config_t;
#endif
